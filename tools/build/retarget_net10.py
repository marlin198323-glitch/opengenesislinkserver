#!/usr/bin/env python3
"""Retarget Prebuild-generated OGL projects from bootstrap net8_0 to net10.0.

The bundled prebuild.dll recognizes net8_0 but not net10_0. Keep using the
working generator and retarget its generated SDK-style project files until
Prebuild itself can be rebuilt and distributed with net10_0 awareness.
"""
from pathlib import Path
import re
import sys

repo = Path(__file__).resolve().parents[2]
paths = []
for folder in ("OpenSim", "NexVerse", "ThirdParty"):
    location = repo / folder
    if location.is_dir():
        paths.extend(location.rglob("*.csproj"))

changed = 0
for path in paths:
    original = path.read_text(encoding="utf-8-sig")
    updated = re.sub(r"(<TargetFramework>)net8\.0(</TargetFramework>)",
                     r"\g<1>net10.0\g<2>", original)
    if updated != original:
        path.write_text(updated, encoding="utf-8")
        changed += 1
    # Any file generated by Prebuild for the current OGL build must use net10.0.
    if "<TargetFramework>net8.0</TargetFramework>" in updated:
        raise SystemExit(f"Old framework remained in {path}")

if changed == 0 and not any("<TargetFramework>net10.0</TargetFramework>"
                            in p.read_text(encoding="utf-8-sig") for p in paths):
    raise SystemExit("No .NET 10 projects found; Prebuild may not have run")

print(f"OGL .NET 10: {changed} generated project files retargeted.")
